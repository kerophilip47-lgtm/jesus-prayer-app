class PrayerApp:
    def __init__(self, root):
        self.root = root
        self.root.title("تطبيق الصلاة اليسوعية والعداد")
        self.root.geometry("500x600")
        self.root.resizable(False, False)

        self.counter = 0
        
        # المسار المباشر لمجلد .spyder-py3 مع الامتدادات الدقيقة للصور
        base_dir = r"C:\Users\SMART TEC\.spyder-py3"
        
        self.bg_images = [
            os.path.join(base_dir, 'background_1.png.jfif'),
            os.path.join(base_dir, 'background_2.png.jpg'),
            os.path.join(base_dir, 'background_3.png.jpg')
        ]
        
        self.current_bg_image = None
        self.current_bg_path = None

        # استخدام Canvas
        self.canvas = tk.Canvas(root, width=500, height=600, highlightthickness=0)
        self.canvas.pack(fill="both", expand=True)

        # تحميل الخلفية الأولى
        self.change_background(forced=True)

        # --- عناصر واجهة المستخدم ---
        self.counter_label = tk.Label(
            root, text=f"العداد: {self.counter}",
            font=("Arial", 28, "bold"), fg="#FFD700", bg="#2a2a2a"
        )
        self.counter_window = self.canvas.create_window(250, 70, window=self.counter_label)

        self.prayer_label = tk.Label(
            root, text=SHORT_PRAYERS[0],
            font=("Arial", 16, "bold"), fg="#FFFFFF", bg="#2a2a2a",
            wraplength=450, justify="center"
        )
        self.prayer_window = self.canvas.create_window(250, 200, window=self.prayer_label)

        self.pray_button = tk.Button(
            root, text="اضغط للعد ✝️ صلاة",
            font=("Arial", 16, "bold"), bg="#2E7D32", fg="white",
            padx=20, pady=10, command=self.on_pray_click,
            relief="raised", bd=3, cursor="hand2"
        )
        self.pray_window_btn = self.canvas.create_window(250, 390, window=self.pray_button)

        self.reset_button = tk.Button(
            root, text="🔄 تصفير العداد",
            font=("Arial", 14, "bold"), bg="#C62828", fg="white",
            padx=15, pady=8, command=self.reset_counter,
            relief="raised", bd=3, cursor="hand2"
        )
        self.reset_window_btn = self.canvas.create_window(250, 470, window=self.reset_button)

    def change_background(self, forced=False):
        try:
            # تتغير الصورة كل 100 مرة أو عند الفتح لأول مرة
            if forced or (self.counter > 0 and self.counter % 100 == 0):
                available_images = [img for img in self.bg_images if img != self.current_bg_path]
                if not available_images:
                    available_images = self.bg_images
                img_path = random.choice(available_images)
                self.current_bg_path = img_path
            else:
                if not self.current_bg_path:
                    self.current_bg_path = self.bg_images[0]
                img_path = self.current_bg_path

            if os.path.exists(img_path):
                img = Image.open(img_path)
                img = img.resize((500, 600), Image.Resampling.LANCZOS)
                self.current_bg_image = ImageTk.PhotoImage(img)
                
                self.canvas.delete("bg")
                self.canvas.create_image(0, 0, image=self.current_bg_image, anchor="nw", tags="bg")
                
                # رفع الأزرار والنصوص فوق الخلفية لتبقى واضحة
                self.canvas.tag_raise(self.counter_window)
                self.canvas.tag_raise(self.prayer_window)
                self.canvas.tag_raise(self.pray_window_btn)
                self.canvas.tag_raise(self.reset_window_btn)
            else:
                print(f"الصورة غير موجودة في المسار: {img_path}")
        except Exception as e:
            print(f"حدث خطأ في تحميل الصورة: {e}")

    def on_pray_click(self):
        self.counter += 1
        self.counter_label.config(text=f"العداد: {self.counter}")

        # اختيار صلاة عشوائية مع كل ضغطة من القائمة الكبيرة
        self.prayer_label.config(text=random.choice(SHORT_PRAYERS))

        # تحديث الخلفية (ستتغير فقط عند مضاعفات العداد 100)
        self.change_background()

        if self.counter % 100 == 0 and self.counter < 1000:
            messagebox.showinfo("بركة وتشجيع! 🕊️", f"رائع جداً! أتممت الآن {self.counter} صلاة.\nاستمر.. 'صَلُّوا بِلاَ انْقِطَاعٍ'")
        elif self.counter >= 1000:
            messagebox.showinfo("مبارك! 👑🎉", "مبارك! أتممت 1000 صلاة يسوعية وبشفاعة القديسين.")
            self.counter = 0
            self.counter_label.config(text=f"العداد: {self.counter}")
            self.change_background(forced=True)

    def reset_counter(self):
        self.counter = 0
        self.counter_label.config(text=f"العداد: {self.counter}")
        self.prayer_label.config(text=SHORT_PRAYERS[0])
        self.change_background(forced=True)

if __name__ == "__main__":
    root = tk.Tk()
    app = PrayerApp(root)
    root.mainloop()
